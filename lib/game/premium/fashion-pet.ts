export function getFashionItemDef(id: string | null | undefined): FashionItemDef | null {
  if (!id) return null
  return PREMIUM_FASHION_ITEMS.find((item) => item.id === id) ?? null
}

export function createDefaultFashionState(): FashionState {
  return {
    unlockedIds: [...STARTER_FASHION_IDS],
    gachaUnlockedIds: [],
    equipped: {
      hat: null,
      hair: null,
      costume: null,
      pants: null,
      shoes: null,
      wings: null,
      back: null,
      accessory: null,
      aura: null,
      weaponSkin: null,
      mountAppearance: null,
    },
  }
}

export function sanitizeFashionState(
  raw: unknown,
  legacy?: {
    ownedGemItems?: string[]
    equippedGemFashion?: string | null
    unlockedCosmetics?: string[]
    equippedWing?: string | null
    equippedWeaponSkin?: string | null
  },
): FashionState {
  const obj = raw && typeof raw === 'object' ? (raw as Partial<FashionState>) : {}
  const validIds = new Set(PREMIUM_FASHION_ITEMS.map((i) => i.id))
  const unlocked = new Set<string>(STARTER_FASHION_IDS)
  if (Array.isArray(obj.unlockedIds)) {
    for (const id of obj.unlockedIds) {
      if (typeof id === 'string' && validIds.has(id)) unlocked.add(id)
    }
  }
  const gachaUnlocked = new Set<string>()
  if (Array.isArray(obj.gachaUnlockedIds)) {
    for (const id of obj.gachaUnlockedIds) {
      if (typeof id === 'string' && validIds.has(id)) {
        gachaUnlocked.add(id)
        unlocked.add(id)
      }
    }
  }

  // Sync legacy unlocked cosmetics & gem fashion automatically
  for (const gemId of legacy?.ownedGemItems ?? []) {
    if (validIds.has(gemId)) unlocked.add(gemId)
  }
  for (const cosId of legacy?.unlockedCosmetics ?? []) {
    if (validIds.has(cosId)) unlocked.add(cosId)
  }

  const eqRaw = obj.equipped && typeof obj.equipped === 'object' ? (obj.equipped as Record<string, unknown>) : {}
  const pick = (slot: FashionSlot, fallback: string | null = null): string | null => {
    const val = eqRaw[slot]
    if (typeof val === 'string' && unlocked.has(val)) {
      const def = getFashionItemDef(val)
      if (def?.slot === slot) return val
    }
    if (fallback && unlocked.has(fallback)) {
      const def = getFashionItemDef(fallback)
      if (def?.slot === slot) return fallback
    }
    return null
  }

  const gemFashion = legacy?.equippedGemFashion ?? null
  const legacyWing = legacy?.equippedWing ?? null
  const legacyWeaponSkin = legacy?.equippedWeaponSkin ?? null

  // Legacy saves might have stored aurora_cat_hood in hair slot before hat slot existed
  const legacyCatHoodFromHair = eqRaw.hair === 'aurora_cat_hood' ? 'aurora_cat_hood' : null

  return {
    unlockedIds: [...unlocked],
    gachaUnlockedIds: [...gachaUnlocked],
    equipped: {
      hat: pick(
        'hat',
        gemFashion === 'aurora_cat_hood' ? 'aurora_cat_hood' : legacyCatHoodFromHair,
      ),
      hair: pick('hair'),
      costume: pick('costume'),
      pants: pick('pants'),
      shoes: pick('shoes'),
      wings: pick(
        'wings',
        legacyWing && validIds.has(legacyWing) ? legacyWing : null,
      ),
      back: pick('back'),
      accessory: pick('accessory'),
      aura: pick('aura', gemFashion === 'sunfire_aura' ? 'sunfire_aura' : null),
      weaponSkin: pick('weaponSkin', legacyWeaponSkin && validIds.has(legacyWeaponSkin) ? legacyWeaponSkin : null),
      mountAppearance: pick('mountAppearance'),
    },
  }
}

